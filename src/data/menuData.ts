export function formatVnd(thousands: number): string {
  return `${(thousands * 1000).toLocaleString('vi-VN')}đ`;
}

export function formatSizeLabel(size: SizeKey): string {
  if (size === 'HOT') return 'Nóng';
  if (size === 'M') return 'Size M';
  if (size === 'L') return 'Size L';
  return 'Phần chuẩn';
}
